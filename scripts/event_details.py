#!/usr/bin/env python3
"""Gather what the reader's event popups show for each event a mention links to (a council or synod).

For each event QID in data/mentions.json: its label and Wikidata description in Latin and each
interface language, when it began and ended (P580/P582, else its point in time P585, as year,
precision and circa), where it was held (P276) and the Wikipedia article title in each interface
language. Needs network access (cached in .cache/wikidata/).

  data/event_details.json   {"$comment": ..., QID: details}

Usage:
  python3 scripts/event_details.py [repo_root]

Standard library only.
"""

import json
import sys
from pathlib import Path

from wikidata import DETAIL_LANGS, Wikidata, _value, life_date

LABEL_LANGS = ("la", *DETAIL_LANGS)
COMMENT = ("What martyrology-frontend's event popups show, by Wikidata item, for each event (council or synod) "
           "data/mentions.json links to: label in Latin and each interface language, description and Wikipedia "
           "title per interface language, start and end (year, negative before Christ; precision; circa) and the "
           "place it was held (P276). Generated by scripts/event_details.py.")


def _place(claims):
    """The place the event was held (P276), preferred statements first; None when there is none."""
    ranked = sorted((c for c in claims.get("P276", []) if c.get("rank") != "deprecated"),
                    key=lambda c: c.get("rank") != "preferred")
    return next((v["id"] for c in ranked if isinstance(v := _value(c), dict) and "id" in v), None)


def summarize(raw):
    claims, labels, descs = raw.get("claims", {}), raw.get("labels", {}), raw.get("descriptions", {})
    links = raw.get("sitelinks", {})
    point = life_date(claims, "P585")
    return {
        "label": {lang: labels[lang]["value"] for lang in LABEL_LANGS if lang in labels},
        "description": {lang: descs[lang]["value"] for lang in DETAIL_LANGS if lang in descs},
        "start": life_date(claims, "P580") or point,
        "end": life_date(claims, "P582") or point,
        "place": _place(claims),
        "wikipedia": {lang: links[f"{lang}wiki"]["title"] for lang in DETAIL_LANGS if f"{lang}wiki" in links},
    }


def _qid_number(qid):
    return int(qid[1:])


def event_qids(mentions_doc):
    """The QIDs that event mentions link to, each once, by number."""
    return sorted({m["qid"] for by_id in mentions_doc["editions"].values() for ms in by_id.values() for m in ms
                   if m["kind"] == "event" and m.get("qid")}, key=_qid_number)


def render_json(details):
    doc = {"$comment": COMMENT, **{q: details[q] for q in sorted(details, key=_qid_number)}}
    return json.dumps(doc, ensure_ascii=False, indent=2) + "\n"


def main(argv):
    repo_root = Path(argv[0]) if argv else Path(__file__).resolve().parent.parent
    data = repo_root / "data"
    qids = event_qids(json.loads((data / "mentions.json").read_text(encoding="utf-8")))
    raws = Wikidata(repo_root / ".cache" / "wikidata").event_entities(qids)
    details = {q: summarize(raws[q]) for q in qids if q in raws}
    (data / "event_details.json").write_text(render_json(details), encoding="utf-8")
    print(f"wrote data/event_details.json: {len(details)} of {len(qids)} events")


if __name__ == "__main__":
    main(sys.argv[1:])
